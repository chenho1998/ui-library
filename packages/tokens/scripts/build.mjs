// Builds @yourorg/tokens: tokens.json -> dist/tokens.css, dist/index.js, dist/index.d.ts
// Also fails the build if any text/background pair misses its contrast target.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { generatePalette, contrast, STEPS } from '../src/palette.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'dist');
mkdirSync(dist, { recursive: true });
const t = JSON.parse(readFileSync(join(root, 'src/tokens.json'), 'utf8'));

// 1. Palettes
const palettes = {};
for (const [name, def] of Object.entries(t.palette)) {
  palettes[name] = generatePalette(def.$value, { chroma: def.$extensions?.chroma });
}

const ref = (value) => value.replace(/\{(\w+)\.(\d+)\}/g, (_, p, s) => `var(--ui-${p}-${s})`);
const resolve = (value) => value.replace(/\{(\w+)\.(\d+)\}/g, (_, p, s) => palettes[p][s]);

// 2. CSS
const lines = [];
const decl = (k, v) => `  --ui-${k}: ${v};`;
lines.push('/* Generated by @yourorg/tokens. Do not edit by hand. */');
lines.push('@layer ui.tokens {');
lines.push(':root {');
for (const [name, steps] of Object.entries(palettes)) {
  for (const s of STEPS) lines.push(decl(`${name}-${s}`, steps[s]));
}
lines.push(decl('font-sans', t.font.sans), decl('font-mono', t.font.mono));
for (const [k, v] of Object.entries(t.font.weight)) lines.push(decl(`font-weight-${k}`, v));
for (const [k, [size, lh]] of Object.entries(t.font.size)) {
  lines.push(decl(`text-${k}`, size), decl(`leading-${k}`, lh));
}
const simple = { space: 'space', control: 'control', icon: 'icon', radius: 'radius', border: 'border', shadow: 'shadow', duration: 'duration', easing: 'easing', z: 'z' };
for (const [group, prefix] of Object.entries(simple)) {
  for (const [k, v] of Object.entries(t[group])) lines.push(decl(`${prefix}-${k}`, v));
}
lines.push('}');
const semanticBlock = (selector, map) => {
  lines.push(`${selector} {`);
  lines.push(`  color-scheme: ${map === t.semantic.dark ? 'dark' : 'light'};`);
  for (const [k, v] of Object.entries(map)) lines.push(decl(`color-${k}`, ref(v)));
  lines.push('}');
};
semanticBlock(":root, [data-theme='light'], [data-theme='system']", t.semantic.light);
semanticBlock("[data-theme='dark']", t.semantic.dark);
lines.push('@media (prefers-color-scheme: dark) {');
semanticBlock("[data-theme='system']", t.semantic.dark);
lines.push('}');
lines.push('}');
writeFileSync(join(dist, 'tokens.css'), lines.join('\n') + '\n');

// 3. JS + types
const resolvedSemantic = {
  light: Object.fromEntries(Object.entries(t.semantic.light).map(([k, v]) => [k, resolve(v)])),
  dark: Object.fromEntries(Object.entries(t.semantic.dark).map(([k, v]) => [k, resolve(v)])),
};
const out = {
  palette: palettes,
  color: resolvedSemantic,
  font: t.font,
  space: t.space,
  control: t.control,
  icon: t.icon,
  radius: t.radius,
  border: t.border,
  shadow: t.shadow,
  duration: t.duration,
  easing: t.easing,
  breakpoint: t.breakpoint,
  z: t.z,
};
copyFileSync(join(root, 'src/palette.js'), join(dist, 'palette.js'));
writeFileSync(
  join(dist, 'index.js'),
  `export * from './palette.js';\nexport const tokens = ${JSON.stringify(out, null, 2)};\n` +
    `export const semanticRefs = ${JSON.stringify(t.semantic, null, 2)};\n` +
    `export const cssVar = (name) => \`var(--ui-\${name})\`;\n`,
);
writeFileSync(
  join(dist, 'index.d.ts'),
  `export declare const STEPS: number[];\n` +
    `export declare function generatePalette(hex: string, opts?: { chroma?: number }): Record<string, string>;\n` +
    `export declare function hexToOklch(hex: string): { l: number; c: number; h: number };\n` +
    `export declare function oklchToHex(color: { l: number; c: number; h: number }): string;\n` +
    `export declare function contrast(a: string, b: string): number;\n` +
    `export declare const tokens: ${JSON.stringify(out, null, 2)};\n` +
    `export declare const semanticRefs: { light: Record<string, string>; dark: Record<string, string> };\n` +
    `export declare const cssVar: (name: string) => string;\n`,
);

// 4. Contrast checks (spec: text 4.5:1, UI borders/icons 3:1)
const checks = [
  ['text-primary', 'bg', 4.5], ['text-primary', 'surface', 4.5], ['text-secondary', 'bg', 4.5],
  ['text-secondary', 'surface-subtle', 4.5], ['text-on-accent', 'accent', 4.5], ['text-on-accent', 'accent-hover', 4.5],
  ['accent-text', 'bg', 4.5], ['danger-text', 'danger-subtle', 4.5], ['success-text', 'success-subtle', 4.5],
  ['warning-text', 'warning-subtle', 4.5], ['info-text', 'info-subtle', 4.5], ['border-strong', 'bg', 3],
  ['focus-ring', 'bg', 3], ['danger', 'bg', 3], ['text-on-accent', 'danger', 4.5],
];
let failed = 0;
for (const scheme of ['light', 'dark']) {
  const s = resolvedSemantic[scheme];
  for (const [fg, bg, min] of checks) {
    // the danger button uses on-accent text over danger
    const ratio = contrast(s[fg], s[bg]);
    if (ratio < min) {
      failed++;
      console.error(`✗ ${scheme}: ${fg} on ${bg} = ${ratio.toFixed(2)} (needs ${min})`);
    }
  }
}
if (failed) {
  console.error(`${failed} contrast check(s) failed`);
  process.exit(1);
}
console.log(`tokens built · ${Object.keys(palettes).length} palettes · ${checks.length * 2} contrast checks passed`);
